(function () {
  const select = document.getElementById("lang");
  const els = document.querySelectorAll("[data-i18n]");
  const en = new Map();
  els.forEach((el) => en.set(el, el.textContent));

  function apply(lang) {
    const dict = I18N[lang] || {};
    els.forEach((el) => { el.textContent = dict[el.dataset.i18n] || en.get(el); });
    document.documentElement.lang = I18N[lang] ? lang : "en";
    select.value = I18N[lang] ? lang : "en";
  }

  // English unless the visitor picked a language (?lang=xx or their saved choice).
  let lang = new URLSearchParams(location.search).get("lang");
  if (!lang) { try { lang = localStorage.getItem("lang"); } catch (e) {} }
  apply(lang || "en");

  select.addEventListener("change", () => {
    const l = select.value;
    apply(l);
    try { localStorage.setItem("lang", l); } catch (e) {}
    const url = new URL(location.href);
    if (l === "en") url.searchParams.delete("lang"); else url.searchParams.set("lang", l);
    history.replaceState(null, "", url);
  });
})();
